"""Export source-backed schemas, catalog labels and decoder fixtures for Android."""
import ast
import hashlib
import json
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
DESKTOP = ROOT.parent / "honda_tuner"
CORE = ROOT / "app/src/main/java/id/hondatuner/core"


def literal_assignment(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == name for target in node.targets):
            return ast.literal_eval(node.value)
    raise ValueError("Missing reference assignment: " + name)


def quote(value):
    return "null" if value is None else json.dumps(value, ensure_ascii=True)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    tree = ast.parse((DESKTOP / "core/diagnostics.py").read_text(encoding="utf-8-sig"))
    schemas = literal_assignment(tree, "_SCHEMAS")
    descriptions = literal_assignment(tree, "DTC_DESCRIPTIONS")
    types = {">B": 0, ">H": 1, ">b": 2, ">e": 3}
    lines = ["// Generated by tools/sync_reference.py from Honda Tuner source.",
             "package id.hondatuner.core;", "", "import java.util.LinkedHashMap;", "import java.util.Map;", "",
             "final class SensorSchemas {", "    private SensorSchemas() {}",
             "    private static Map<Integer, String> ethanol() {", "        Map<Integer, String> result = new LinkedHashMap<>();"]
    enum_sets = [options for fields in schemas.values() for _, _, _, _, options in fields if isinstance(options, dict)]
    if any(options != enum_sets[0] for options in enum_sets):
        raise ValueError("New enum schema needs an explicit generator update")
    for key, value in (enum_sets[0] if enum_sets else {}).items():
        lines.append("        result.put(%d, %s);" % (key, quote(value)))
    lines += ["        return result;", "    }", "    private static final SensorDecoder.Schema[] SCHEMAS = {"]
    for (table, size), fields in schemas.items():
        lines.append("        new SensorDecoder.Schema(0x%02X, %d," % (table, size))
        for index, (name, offset, fmt, conversion, options) in enumerate(fields):
            bits = "new String[]{%s}" % ", ".join(quote(value) for value in options) if isinstance(options, tuple) else "null"
            labels = "ethanol()" if isinstance(options, dict) else "null"
            ending = ")," if index != len(fields) - 1 else ")) ,"
            lines.append("            new SensorDecoder.Field(%s, %d, %d, %s, %s, %s%s" %
                         (quote(name), offset, types[fmt], quote(conversion), bits, labels, ending))
    lines += ["    };", "    static SensorDecoder.Schema find(int table, int length) {",
              "        for (SensorDecoder.Schema schema : SCHEMAS) if (schema.table == table && schema.length == length) return schema;",
              "        return null;", "    }", "}", ""]
    CORE.mkdir(parents=True, exist_ok=True)
    (CORE / "SensorSchemas.java").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    lines = ["// Generated from the desktop source DTC description catalog.", "package id.hondatuner.core;", "",
             "import java.util.LinkedHashMap;", "import java.util.Map;", "", "public final class DtcDescriptions {",
             "    private DtcDescriptions() {}", "    private static final Map<String, String> ITEMS = new LinkedHashMap<>();", "    static {"]
    for key, value in descriptions.items():
        lines.append("        ITEMS.put(%s, %s);" % (quote(key), quote(value)))
    lines += ["    }", "    public static String describe(String code) {",
              '        return ITEMS.containsKey(code) ? ITEMS.get(code) : "DTC belum ada dalam katalog: " + code;', "    }", "}", ""]
    (CORE / "DtcDescriptions.java").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    catalog = json.loads((DESKTOP / "data/ecudb.json").read_text(encoding="utf-8-sig"))
    labels = []
    for entry in catalog:
        identifier = (entry["ecmid_model"] + entry["ecmid_region"]).upper()
        if len(identifier) != 10 or identifier == "FFFFFFFFFF":
            continue
        labels.append("\t".join(str(value or "").replace("\t", " ").replace("\n", " ").replace("\r", " ")
                                for value in (identifier, entry["model"], entry.get("ecu_pn"))))
    assets = ROOT / "app/src/main/assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "ecu_catalog.tsv").write_text("\n".join(labels) + "\n", encoding="utf-8", newline="\n")

    sys.path.insert(0, str(DESKTOP))
    from core.diagnostics import decode_table
    vectors = []
    rng = random.Random(20261115)
    for table, size in schemas:
        bodies = [bytes(size), bytes([255]) * size, bytes(range(size)), bytes([128]) * size]
        bodies.extend(bytes(rng.randrange(256) for _ in range(size)) for _ in range(20))
        for body in bodies:
            values = {}
            for name, value in decode_table(table, body).items():
                if isinstance(value, dict):
                    values.update((name + "." + key, bit) for key, bit in value.items())
                else:
                    if isinstance(value, float) and (value != value or value in (float("inf"), float("-inf"))):
                        value = "NaN" if value != value else "Infinity" if value > 0 else "-Infinity"
                    values[name] = value
            vectors.append({"table": table, "body": body.hex().upper(), "values": values})
    tests = ROOT / "tests"
    tests.mkdir(parents=True, exist_ok=True)
    (tests / "reference_vectors.json").write_text(json.dumps(vectors, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    source_paths = ["core/commands.py", "core/diagnostics.py", "core/live.py", "core/session.py", "core/protocol.py", "core/ftdi_source.py", "ui/live.py", "data/ecudb.json"]
    generated = [CORE / "SensorSchemas.java", CORE / "DtcDescriptions.java", assets / "ecu_catalog.tsv", tests / "reference_vectors.json"]
    evidence = {
        "reference": "Existing independent Honda Tuner source; no original native binary was modified or loaded.",
        "reference_sha256": {name: digest(DESKTOP / name) for name in source_paths},
        "generated_sha256": {path.relative_to(ROOT).as_posix(): digest(path) for path in generated},
        "schema_variants": len(schemas), "decoder_vectors": len(vectors), "catalog_rows": len(labels),
        "physical_android_usb_or_ecu_validation": False,
        "new_rea_evidence_claimed": False,
    }
    (ROOT / "evidence").mkdir(exist_ok=True)
    (ROOT / "evidence/reference_provenance.json").write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8", newline="\n")
    print("Exported %d schema variants, %d decoder vectors and %d exact-ID catalog rows." % (len(schemas), len(vectors), len(labels)))


if __name__ == "__main__":
    main()
